-- Demo "shop" schema. Loaded by the postgres image's init hook on first start.
-- Deliberately close to what a real Rails/Django-era storefront looks like,
-- including a few legacy rough edges the demo migrations then try to fix:
--   * orders.user_id is nullable (old guest-checkout code path)    -> 005_not_null.sql
--   * payments.order_id has no foreign key                          -> 003_fk_payments.sql
--   * orders.total is unconstrained numeric                         -> 004_alter_type.sql
--   * no index on orders.created_at (admin report scans)            -> 002_index_orders_created.sql

CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

CREATE TYPE order_status AS ENUM ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded');
CREATE TYPE payment_status AS ENUM ('authorized', 'captured', 'failed', 'refunded');

CREATE TABLE users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text        NOT NULL,
    name        text        NOT NULL,
    country     char(2)     NOT NULL DEFAULT 'US',
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text          NOT NULL UNIQUE,
    name         text          NOT NULL,
    category     text          NOT NULL,
    price        numeric(10,2) NOT NULL CHECK (price >= 0),
    stock        integer       NOT NULL DEFAULT 0,
    description  text,
    created_at   timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX products_category_idx ON products (category);

CREATE TABLE orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint REFERENCES users (id),
    status      order_status NOT NULL DEFAULT 'pending',
    total       numeric      NOT NULL DEFAULT 0,
    currency    char(3)      NOT NULL DEFAULT 'USD',
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX orders_user_id_idx ON orders (user_id);
-- Fulfilment workers poll for unshipped orders.
CREATE INDEX orders_open_status_idx ON orders (status) WHERE status IN ('pending', 'paid');

CREATE TABLE order_items (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id  bigint        NOT NULL REFERENCES products (id),
    quantity    integer       NOT NULL CHECK (quantity > 0),
    unit_price  numeric(10,2) NOT NULL
);
CREATE INDEX order_items_order_id_idx ON order_items (order_id);
CREATE INDEX order_items_product_id_idx ON order_items (product_id);

CREATE TABLE payments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint         NOT NULL,          -- legacy: no FK (see 003_fk_payments.sql)
    provider     text           NOT NULL,
    provider_ref text           NOT NULL,
    amount       numeric(12,2)  NOT NULL,
    status       payment_status NOT NULL,
    created_at   timestamptz    NOT NULL DEFAULT now()
);
CREATE INDEX payments_order_id_idx ON payments (order_id);

-- Finance dashboard: revenue per day and category.
CREATE VIEW daily_revenue AS
SELECT date_trunc('day', o.created_at)::date    AS day,
       p.category,
       count(DISTINCT o.id)                     AS orders,
       sum(oi.quantity * oi.unit_price)         AS revenue
FROM orders o
JOIN order_items oi ON oi.order_id = o.id
JOIN products p     ON p.id = oi.product_id
WHERE o.status IN ('paid', 'shipped', 'delivered')
GROUP BY 1, 2;
