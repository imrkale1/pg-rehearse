func scalar[T any](t *testing.T, pool *pgxpool.Pool, sql string, args ...any) T {
	t.Helper()
	var v T
	if err := pool.QueryRow(context.Background(), sql, args...).Scan(&v); err != nil {
		t.Fatalf("%s: %v", sql, err)
	}
	return v
}

func near(t *testing.T, what string, got, want, tol float64) {
	t.Helper()
	if math.Abs(got-want) > tol {
		t.Errorf("%s = %.4f, want %.4f ± %.4f", what, got, want, tol)
	}
}

func TestBuildShop(t *testing.T) {
	pool := freshDB(t)
	ctx := context.Background()
	Logf = t.Logf
	defer func() { Logf = func(string, ...any) {} }()

	start := time.Now()
	if err := Build(ctx, pool, shopProfile(), Options{Scale: 0.1, Seed: 42}); err != nil {
		t.Fatalf("Build: %v", err)
	}
	el := time.Since(start)

	// Row counts.
	want := map[string]int64{"users": 50_000, "categories": 200, "products": 2_000, "orders": 200_000, "order_items": 500_000}
	var total int64
	for tbl, n := range want {
		got := scalar[int64](t, pool, "SELECT count(*) FROM public."+tbl)
		total += got
		if tbl == "order_items" { // composite PK: colliding rows may be dropped
			if got > n || got < n*99/100 {
				t.Errorf("%s: %d rows, want ~%d", tbl, got, n)
			}
		} else if got != n {
			t.Errorf("%s: %d rows, want %d", tbl, got, n)
		}
	}
	t.Logf("built %d rows in %s: %.0f rows/sec (schema + load + indexes + FKs + ANALYZE)", total, el.Round(time.Millisecond), float64(total)/el.Seconds())

	// FK integrity: constraints are back and validated, and no orphans exist.
	if n := scalar[int64](t, pool, `SELECT count(*) FROM pg_constraint WHERE contype = 'f' AND convalidated`); n != 5 {
		t.Errorf("validated foreign keys = %d, want 5", n)
	}
	for name, q := range map[string]string{
		"orders.user_id":         `SELECT count(*) FROM orders o LEFT JOIN users u ON u.id = o.user_id WHERE u.id IS NULL`,
		"order_items.order_id":   `SELECT count(*) FROM order_items i LEFT JOIN orders o ON o.id = i.order_id WHERE o.id IS NULL`,
		"order_items.product_id": `SELECT count(*) FROM order_items i LEFT JOIN products p ON p.id = i.product_id WHERE p.id IS NULL`,
		"products.category_id":   `SELECT count(*) FROM products p LEFT JOIN categories c ON c.id = p.category_id WHERE c.id IS NULL`,
		"categories.parent_id":   `SELECT count(*) FROM categories c LEFT JOIN categories p ON p.id = c.parent_id WHERE c.parent_id IS NOT NULL AND p.id IS NULL`,
	} {
		if n := scalar[int64](t, pool, q); n != 0 {
			t.Errorf("%s: %d orphan rows", name, n)
		}
	}
	// Self-referencing categories form a forest (no cycles) with roots and children.
	if n := scalar[int64](t, pool, `
WITH RECURSIVE tree AS (
  SELECT id, 1 AS depth FROM categories WHERE parent_id IS NULL
  UNION ALL SELECT c.id, t.depth + 1 FROM categories c JOIN tree t ON c.parent_id = t.id WHERE t.depth < 1000)
SELECT count(*) FROM tree`); n != 200 {
		t.Errorf("categories reachable from roots = %d, want 200", n)
	}
	near(t, "categories.parent_id null frac", scalar[float64](t, pool, `SELECT avg((parent_id IS NULL)::int)::float8 FROM categories`), 0.2, 0.1)

	// Indexes, checks and secondary structures are restored.
	if n := scalar[int64](t, pool, `SELECT count(*) FROM pg_indexes WHERE schemaname = 'public'`); n != 10 {
		t.Errorf("indexes = %d, want 10", n)
	}
	if n := scalar[int64](t, pool, `SELECT count(*) FROM pg_constraint WHERE contype = 'c' AND convalidated AND conname = 'products_price_check'`); n != 1 {
		t.Errorf("check constraint not restored")
	}

	// Null fractions.
	near(t, "orders.coupon null frac", scalar[float64](t, pool, `SELECT avg((coupon IS NULL)::int)::float8 FROM orders`), 0.7, 0.01)
	near(t, "users.country null frac", scalar[float64](t, pool, `SELECT avg((country IS NULL)::int)::float8 FROM users`), 0.1, 0.01)
	near(t, "order_items.unit_price null frac", scalar[float64](t, pool, `SELECT avg((unit_price IS NULL)::int)::float8 FROM order_items`), 0.05, 0.01)
	near(t, "products.attrs null frac", scalar[float64](t, pool, `SELECT avg((attrs IS NULL)::int)::float8 FROM products`), 0.3, 0.04)

	// Most common values.
	for st, f := range statusFreqs {
		near(t, "orders.status="+st, scalar[float64](t, pool, `SELECT avg((status = $1::order_status)::int)::float8 FROM orders`, st), f, 0.01)
	}
	for c, f := range map[string]float64{"US": 0.45, "DE": 0.18, "FR": 0.09} {
		near(t, "users.country="+c, scalar[float64](t, pool, `SELECT (count(*) FILTER (WHERE country = $1))::float8 / count(*) FROM users`, c), f, 0.01)
	}
	near(t, "orders.coupon=WELCOME10", scalar[float64](t, pool, `SELECT (count(*) FILTER (WHERE coupon = 'WELCOME10'))::float8 / count(*) FROM orders`), 0.15, 0.01)
	near(t, "order_items.quantity=1", scalar[float64](t, pool, `SELECT avg((quantity = 1)::int)::float8 FROM order_items`), 0.6, 0.02)
	near(t, "products.active", scalar[float64](t, pool, `SELECT avg(active::int)::float8 FROM products`), 0.9, 0.03)

	// n_distinct.
	if n := scalar[int64](t, pool, `SELECT count(DISTINCT coupon) FROM orders`); n < 20 || n > 40 {
		t.Errorf("distinct coupons = %d, want <= 40 and close to it", n)
	}
	if n := scalar[int64](t, pool, `SELECT count(DISTINCT country) FROM users`); n != 6 {
		t.Errorf("distinct countries = %d, want 6", n)
	}
	if n := scalar[int64](t, pool, `SELECT count(DISTINCT user_id) FROM orders`); n < 30_000 || n > 40_000 {
		t.Errorf("distinct orders.user_id = %d, want <= 40000 (n_distinct -0.2)", n)
	}

	// Histograms.
	near(t, "orders.total median", scalar[float64](t, pool, `SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY total)::float8 FROM orders`), 50, 2)
	near(t, "orders.total <= 120 share", scalar[float64](t, pool, `SELECT avg((total <= 120)::int)::float8 FROM orders`), 0.75, 0.01)
	if ok := scalar[bool](t, pool, `SELECT min(total) >= 1 AND max(total) <= 5000 AND min(created_at) >= '2022-01-01+00' AND max(created_at) <= '2024-06-30 12:00+00' FROM orders`); !ok {
		t.Errorf("orders.total / created_at outside histogram bounds")
	}
	near(t, "orders created before 2023", scalar[float64](t, pool, `SELECT avg((created_at < '2023-01-01+00')::int)::float8 FROM orders`), 1.0/3, 0.02)
	if c := scalar[float64](t, pool, `SELECT corr(id::float8, extract(epoch FROM created_at)::float8) FROM orders`); c < 0.9 {
		t.Errorf("orders.created_at correlation with id = %.3f, want > 0.9", c)
	}
	if ok := scalar[bool](t, pool, `SELECT min(price) >= 0.99 AND max(price) <= 499 AND max(length(title)) <= 40 FROM products`); !ok {
		t.Errorf("products.price / title out of bounds")
	}
	near(t, "users.name avg width", scalar[float64](t, pool, `SELECT avg(length(name))::float8 FROM users`), 13, 5)

	// Uniqueness and fake values for sensitive columns.
	if n := scalar[int64](t, pool, `SELECT count(DISTINCT email) FROM users`); n != 50_000 {
		t.Errorf("distinct emails = %d, want 50000", n)
	}
	if n := scalar[int64](t, pool, `SELECT count(*) FROM users WHERE email !~ '^user[0-9]+@example\.test$'`); n != 0 {
		t.Errorf("%d emails are not fake", n)
	}
	if n := scalar[int64](t, pool, `SELECT count(DISTINCT sku) FROM products`); n != 2_000 {
		t.Errorf("distinct skus = %d, want 2000", n)
	}
	if n := scalar[int64](t, pool, `SELECT count(*) FROM (SELECT 1 FROM order_items GROUP BY order_id, product_id HAVING count(*) > 1) d`); n != 0 {
		t.Errorf("%d duplicate order_items keys", n)
	}
	if n := scalar[int64](t, pool, `SELECT count(*) FROM products WHERE attrs IS NOT NULL AND jsonb_typeof(attrs) <> 'object'`); n != 0 {
		t.Errorf("%d bad jsonb values", n)
	}

	// Zipf-ish skew: the busiest 1% of users place far more than 1% of orders.
	share := scalar[float64](t, pool, `
SELECT sum(n)::float8 / (SELECT count(*) FROM orders)
FROM (SELECT count(*) AS n FROM orders GROUP BY user_id ORDER BY n DESC LIMIT 500) s`)
	if share < 0.05 {
		t.Errorf("top 1%% of users hold %.1f%% of orders, want skew (> 5%%)", share*100)
	}
	t.Logf("top 1%% of users hold %.1f%% of orders", share*100)

	// Sequences continue after the loaded data.
	var uid, cid int64
	if err := pool.QueryRow(ctx, `INSERT INTO users (email, name) VALUES ('new@example.test', 'New User') RETURNING id`).Scan(&uid); err != nil || uid != 50_001 {
		t.Errorf("insert into users after load: id=%d err=%v", uid, err)
	}
	if err := pool.QueryRow(ctx, `INSERT INTO categories (name) VALUES ('new') RETURNING id`).Scan(&cid); err != nil || cid != 201 {
		t.Errorf("insert into categories after load: id=%d err=%v", cid, err)
	}
	// ANALYZE ran.
	if n := scalar[int64](t, pool, `SELECT count(*) FROM pg_stats WHERE schemaname = 'public' AND tablename = 'orders'`); n == 0 {
		t.Errorf("orders was not analyzed")
	}
}

func tableHashes(t *testing.T, pool *pgxpool.Pool) string {
	t.Helper()
	var sb strings.Builder
	for _, tbl := range []string{"users", "categories", "products", "orders", "order_items"} {
		h := scalar[string](t, pool, fmt.Sprintf(`SELECT coalesce(md5(string_agg(x::text, '|' ORDER BY x::text)), '') FROM public.%s x`, tbl))
		fmt.Fprintf(&sb, "%s=%s ", tbl, h)
	}
	return sb.String()
}

func TestBuildDeterministic(t *testing.T) {
	build := func(seed int64, batch int) string {
		pool := freshDB(t)
		if err := Build(context.Background(), pool, shopProfile(), Options{Scale: 0.01, Seed: seed, BatchRows: batch}); err != nil {
			t.Fatalf("Build: %v", err)
		}
		return tableHashes(t, pool)
	}
	a, b, c := build(7, 3000), build(7, 3000), build(8, 3000)
	if a != b {
		t.Errorf("same seed produced different data:\n%s\n%s", a, b)
	}
	if a == c {
		t.Errorf("different seeds produced identical data")
	}
}

// A two-table FK cycle with NOT NULL on both sides, a table missing from the
// profile, a user trigger and a generated column.
func TestBuildCycleAndDefaults(t *testing.T) {
	pool := freshDB(t)
	ctx := context.Background()
	p := &model.Profile{
		SchemaSQL: `
CREATE TABLE public.teams (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, lead_id uuid NOT NULL, name text NOT NULL,
    slug text GENERATED ALWAYS AS (lower(name)) STORED);
CREATE TABLE public.members (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), team_id bigint NOT NULL, boss_id uuid, joined date NOT NULL, tags text[]);
CREATE TABLE public.audit (id bigserial PRIMARY KEY, note text);
CREATE TABLE public.unprofiled (id int PRIMARY KEY, team_id bigint REFERENCES public.teams(id));
ALTER TABLE public.teams ADD CONSTRAINT teams_lead_fk FOREIGN KEY (lead_id) REFERENCES public.members(id);
ALTER TABLE public.members ADD CONSTRAINT members_team_fk FOREIGN KEY (team_id) REFERENCES public.teams(id);
ALTER TABLE public.members ADD CONSTRAINT members_boss_fk FOREIGN KEY (boss_id) REFERENCES public.members(id);
CREATE FUNCTION public.audit_member() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN INSERT INTO public.audit(note) VALUES ('member'); RETURN NEW; END $$;
CREATE TRIGGER members_audit AFTER INSERT ON public.members FOR EACH ROW EXECUTE FUNCTION public.audit_member();
`,
		Tables: []model.TableProfile{
			{Schema: "public", Name: "teams", RowEstimate: 300},
			{Schema: "public", Name: "members", RowEstimate: 5000, Columns: []model.ColumnProfile{
				{Name: "boss_id", Nullable: true, NullFrac: 0.1},
				{Name: "joined", HistogramBounds: []string{"2020-01-01", "2021-01-01"}},
			}},
			{Schema: "public", Name: "ghost", RowEstimate: 10},
		},
	}
	if err := Build(ctx, pool, p, Options{Scale: 1, Seed: 1, BatchRows: 1000}); err != nil {
		t.Fatalf("Build: %v", err)
	}
	for q, want := range map[string]int64{
		`SELECT count(*) FROM teams`:      300,
		`SELECT count(*) FROM members`:    5000,
		`SELECT count(*) FROM unprofiled`: 0,
		`SELECT count(*) FROM audit`:      0, // trigger disabled during the load
		`SELECT count(*) FROM teams t LEFT JOIN members m ON m.id = t.lead_id WHERE m.id IS NULL`:                             0,
		`SELECT count(*) FROM members m LEFT JOIN teams t ON t.id = m.team_id WHERE t.id IS NULL`:                             0,
		`SELECT count(*) FROM members m LEFT JOIN members b ON b.id = m.boss_id WHERE m.boss_id IS NOT NULL AND b.id IS NULL`: 0,
		`SELECT count(*) FROM members WHERE joined < '2020-01-01' OR joined > '2021-01-01'`:                                   0,
		`SELECT count(*) FROM teams WHERE slug IS DISTINCT FROM lower(name)`:                                                  0,
		`SELECT count(*) FROM pg_constraint WHERE contype = 'f' AND convalidated`:                                             4,
		`SELECT count(*) FROM pg_attribute WHERE attrelid = 'teams'::regclass AND attname = 'lead_id' AND attnotnull`:         1,
		`SELECT count(*) FROM pg_trigger WHERE tgname = 'members_audit' AND tgenabled = 'O'`:                                  1,
		`SELECT (count(*) FILTER (WHERE boss_id IS NULL) BETWEEN 350 AND 650)::int FROM members`:                              1,
		`SELECT (count(DISTINCT lead_id) > 100)::int FROM teams`:                                                              1,
	} {
		if got := scalar[int64](t, pool, q); got != want {
			t.Errorf("%s = %d, want %d", q, got, want)
		}
	}
}

