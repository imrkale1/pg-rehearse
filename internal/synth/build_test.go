// freshDB creates a new empty database on the server named by PGR_TEST_DSN and
// returns a pool connected to it. The database is dropped when the test ends.
func freshDB(t *testing.T) *pgxpool.Pool {
	t.Helper()
	dsn := os.Getenv("PGR_TEST_DSN")
	if dsn == "" {
		t.Skip("PGR_TEST_DSN not set")
	}
	ctx := context.Background()
	admin, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatalf("connect: %v", err)
	}
	name := fmt.Sprintf("pgr_synth_%d_%d", os.Getpid(), time.Now().UnixNano())
	if _, err := admin.Exec(ctx, "CREATE DATABASE "+name); err != nil {
		t.Fatalf("create database: %v", err)
	}
	u, err := url.Parse(dsn)
	if err != nil {
		t.Fatalf("PGR_TEST_DSN must be a URL: %v", err)
	}
	u.Path = "/" + name
	pool, err := pgxpool.New(ctx, u.String())
	if err != nil {
		t.Fatalf("pool: %v", err)
	}
	t.Cleanup(func() {
		pool.Close()
		if _, err := admin.Exec(ctx, "DROP DATABASE IF EXISTS "+name+" WITH (FORCE)"); err != nil {
			t.Logf("drop database: %v", err)
		}
		admin.Close(ctx)
	})
	return pool
}

const shopSchema = `
SET check_function_bodies = false;
CREATE TYPE public.order_status AS ENUM ('pending', 'paid', 'shipped', 'cancelled', 'refunded');
CREATE TABLE public.users (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    name text NOT NULL,
    country character varying(2),
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON public.users USING btree (email);
CREATE TABLE public.categories (
    id serial PRIMARY KEY,
    parent_id integer,
    name text NOT NULL
);
CREATE TABLE public.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku uuid NOT NULL UNIQUE,
    category_id integer NOT NULL,
    title character varying(40) NOT NULL,
    price numeric(10,2) NOT NULL CONSTRAINT products_price_check CHECK (price >= 0),
    attrs jsonb,
    active boolean NOT NULL
);
CREATE TABLE public.orders (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    status public.order_status NOT NULL,
    total numeric(12,2) NOT NULL,
    coupon text,
    created_at timestamp with time zone NOT NULL
);
CREATE TABLE public.order_items (
    order_id bigint NOT NULL,
    product_id bigint NOT NULL,
    quantity integer NOT NULL,
    unit_price numeric(10,2),
    PRIMARY KEY (order_id, product_id)
);
CREATE INDEX orders_user_id_idx ON public.orders USING btree (user_id);
CREATE INDEX orders_created_at_idx ON public.orders USING btree (created_at);
CREATE INDEX order_items_product_id_idx ON public.order_items USING btree (product_id);
ALTER TABLE public.categories ADD CONSTRAINT categories_parent_id_fkey FOREIGN KEY (parent_id) REFERENCES public.categories(id);
ALTER TABLE public.products ADD CONSTRAINT products_category_id_fkey FOREIGN KEY (category_id) REFERENCES public.categories(id);
ALTER TABLE public.orders ADD CONSTRAINT orders_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(id);
ALTER TABLE public.order_items ADD CONSTRAINT order_items_order_id_fkey FOREIGN KEY (order_id) REFERENCES public.orders(id) ON DELETE CASCADE;
ALTER TABLE public.order_items ADD CONSTRAINT order_items_product_id_fkey FOREIGN KEY (product_id) REFERENCES public.products(id);
`

