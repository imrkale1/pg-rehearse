// Integration tests run against a real server when PGR_TEST_DSN is set, e.g.
//   PGR_TEST_DSN=postgres://postgres:pg@localhost:55431/postgres?sslmode=disable
// The server needs shared_preload_libraries = 'pg_stat_statements'. Each test
// creates and drops its own database(s).

func testDSN(t *testing.T) string {
	t.Helper()
	dsn := os.Getenv("PGR_TEST_DSN")
	if dsn == "" {
		t.Skip("PGR_TEST_DSN not set; skipping integration test")
	}
	return dsn
}

var dbSeq atomic.Int64

// newTestDB creates a fresh database and returns a pool connected to it.
// The database is dropped at test cleanup.
func newTestDB(t *testing.T, withPSS bool) *pgxpool.Pool {
	t.Helper()
	dsn := testDSN(t)
	ctx := context.Background()
	admin, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatalf("connect admin: %v", err)
	}
	name := fmt.Sprintf("pgr_profile_it_%d_%d", time.Now().UnixNano()%1e9, dbSeq.Add(1))
	if _, err := admin.Exec(ctx, "CREATE DATABASE "+name); err != nil {
		admin.Close(ctx)
		t.Fatalf("create database: %v", err)
	}
	admin.Close(ctx)

	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.Database = name
	cfg.MaxConns = 20
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatalf("connect %s: %v", name, err)
	}
	t.Cleanup(func() {
		pool.Close()
		c, err := pgx.Connect(context.Background(), dsn)
		if err != nil {
			t.Logf("cleanup connect: %v", err)
			return
		}
		defer c.Close(context.Background())
		if _, err := c.Exec(context.Background(), "DROP DATABASE IF EXISTS "+name+" WITH (FORCE)"); err != nil {
			t.Logf("drop %s: %v", name, err)
		}
	})
	if withPSS {
		mustExec(t, pool, "CREATE EXTENSION IF NOT EXISTS pg_stat_statements")
	}
	return pool
}

func mustExec(t *testing.T, pool *pgxpool.Pool, sql string, args ...any) {
	t.Helper()
	if _, err := pool.Exec(context.Background(), sql, args...); err != nil {
		t.Fatalf("exec %q: %v", truncate(sql, 80), err)
	}
}

const fixtureSchema = `
CREATE TYPE order_status AS ENUM ('pending', 'paid', 'shipped', 'cancelled');
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE orders (
    id serial PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    status order_status NOT NULL DEFAULT 'pending',
    total numeric(12,2) NOT NULL CHECK (total >= 0),
    shipped_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT orders_id_user_key UNIQUE (id, user_id)
);
CREATE TABLE order_items (
    order_id integer NOT NULL,
    user_id bigint NOT NULL,
    line_no integer NOT NULL,
    sku text NOT NULL,
    qty integer NOT NULL DEFAULT 1 CONSTRAINT qty_positive CHECK (qty > 0),
    PRIMARY KEY (order_id, line_no),
    CONSTRAINT order_items_order_fk FOREIGN KEY (order_id, user_id) REFERENCES orders(id, user_id) ON DELETE CASCADE
);
CREATE INDEX orders_pending_idx ON orders (created_at) WHERE status = 'pending';
CREATE INDEX orders_user_idx ON orders (user_id);
CREATE VIEW paid_orders AS
    SELECT o.id, o.user_id, u.email, o.total FROM orders o JOIN users u ON u.id = o.user_id
    WHERE o.status = 'paid';
CREATE SCHEMA billing;
CREATE TABLE billing."Invoices" (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id),
    "AmountDue" numeric NOT NULL
);
`

// catalogFingerprint describes the user objects of a database as sorted text lines.
func catalogFingerprint(t *testing.T, pool *pgxpool.Pool) []string {
	t.Helper()
	q := `
SELECT 'table ' || n.nspname || '.' || c.relname || ' ' || c.relkind::text FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname IN ('public','billing') AND c.relkind IN ('r','p','v','m','S')
UNION ALL
SELECT format('column %s.%s %s notnull=%s identity=%s default=%s', c.relname, a.attname,
              format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attidentity,
              coalesce(pg_get_expr(ad.adbin, ad.adrelid), ''))
  FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
  LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
  WHERE n.nspname IN ('public','billing') AND c.relkind IN ('r','v') AND a.attnum > 0 AND NOT a.attisdropped
UNION ALL
SELECT format('constraint %s %s %s %s', c.relname, co.conname, co.contype, pg_get_constraintdef(co.oid))
  FROM pg_constraint co JOIN pg_class c ON c.oid = co.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname IN ('public','billing')
UNION ALL
SELECT format('index %s %s', indexname, indexdef) FROM pg_indexes WHERE schemaname IN ('public','billing')
UNION ALL
SELECT format('view %s %s', viewname, definition) FROM pg_views WHERE schemaname IN ('public','billing')
UNION ALL
SELECT format('type %s %s', t.typname,
              (SELECT string_agg(enumlabel, ',' ORDER BY enumsortorder) FROM pg_enum WHERE enumtypid = t.oid))
  FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname IN ('public','billing') AND t.typtype = 'e'
UNION ALL
SELECT format('seqowner %s %s.%s', s.relname, t.relname, a.attname)
  FROM pg_class s JOIN pg_depend d ON d.objid = s.oid AND d.classid = 'pg_class'::regclass AND d.deptype IN ('a','i')
  JOIN pg_class t ON t.oid = d.refobjid JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
  JOIN pg_namespace n ON n.oid = s.relnamespace
  WHERE s.relkind = 'S' AND n.nspname IN ('public','billing')`
	rows, err := pool.Query(context.Background(), q)
	if err != nil {
		t.Fatalf("fingerprint: %v", err)
	}
	lines, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		t.Fatalf("fingerprint: %v", err)
	}
	sort.Strings(lines)
	return lines
}

func findTable(p *model.Profile, name string) *model.TableProfile {
	for i := range p.Tables {
		if p.Tables[i].QualifiedName() == name {
			return &p.Tables[i]
		}
	}
	return nil
}

func findColumn(t *model.TableProfile, name string) *model.ColumnProfile {
	for i := range t.Columns {
		if t.Columns[i].Name == name {
			return &t.Columns[i]
		}
	}
	return nil
}

func TestIntegrationSchemaRoundTrip(t *testing.T) {
	src := newTestDB(t, true)
	mustExec(t, src, fixtureSchema)
	ctx := context.Background()

	p, err := Collect(ctx, src, Options{SampleInterval: 200 * time.Millisecond})
	if err != nil {
		t.Fatalf("Collect: %v", err)
	}
	for _, want := range []string{"public.users", "public.orders", "public.order_items"} {
		if findTable(p, want) == nil {
			t.Errorf("profile missing table %s", want)
		}
	}

	t.Logf("SchemaSQL:\n%s", p.SchemaSQL)
	dst := newTestDB(t, false)
	if _, err := dst.Exec(ctx, p.SchemaSQL); err != nil {
		t.Fatalf("apply SchemaSQL: %v\n%s", err, p.SchemaSQL)
	}

	a, b := catalogFingerprint(t, src), catalogFingerprint(t, dst)
	if strings.Join(a, "\n") != strings.Join(b, "\n") {
		t.Errorf("catalogs differ\n--- source\n%s\n--- copy\n%s\n--- SchemaSQL\n%s",
			strings.Join(a, "\n"), strings.Join(b, "\n"), p.SchemaSQL)
	}
	for _, kind := range []string{"view paid_orders", "index orders_pending_idx", "constraint order_items order_items_order_fk",
		"constraint orders orders_total_check", "constraint order_items qty_positive"} {
		found := false
		for _, l := range b {
			if strings.HasPrefix(l, kind) {
				found = true
			}
		}
		if !found {
			t.Errorf("copy lacks %q", kind)
		}
	}

	// Default ids, defaults and constraints work on the copy.
	var uid int64
	if err := dst.QueryRow(ctx, "INSERT INTO users (email, name) VALUES ('a@x', 'A') RETURNING id").Scan(&uid); err != nil {
		t.Fatalf("insert user: %v", err)
	}
	var oid int32
	var status string
	if err := dst.QueryRow(ctx, "INSERT INTO orders (user_id, total) VALUES ($1, 9.99) RETURNING id, status::text", uid).Scan(&oid, &status); err != nil {
		t.Fatalf("insert order: %v", err)
	}
	if status != "pending" {
		t.Errorf("default status = %q", status)
	}
	if _, err := dst.Exec(ctx, "INSERT INTO order_items (order_id, user_id, line_no, sku) VALUES ($1, $2, 1, 'X')", oid, uid); err != nil {
		t.Fatalf("insert item: %v", err)
	}
	if _, err := dst.Exec(ctx, "INSERT INTO order_items (order_id, user_id, line_no, sku) VALUES ($1, $2, 2, 'X')", oid, uid+1); err == nil {
		t.Errorf("composite FK not enforced on copy")
	}
	if _, err := dst.Exec(ctx, "INSERT INTO orders (user_id, total) VALUES ($1, -1)", uid); err == nil {
		t.Errorf("check constraint not enforced on copy")
	}
	var n int
	if err := dst.QueryRow(ctx, "SELECT count(*) FROM paid_orders").Scan(&n); err != nil {
		t.Errorf("query view: %v", err)
	}
}

// seed fills the fixture with nUsers users and nOrders orders, then ANALYZEs.
func seed(t *testing.T, pool *pgxpool.Pool, nUsers, nOrders int) {
	t.Helper()
	mustExec(t, pool, fixtureSchema)
	mustExec(t, pool, `INSERT INTO users (email, name)
SELECT 'user' || g || '@example.com', 'Name ' || (g % 997) FROM generate_series(1, $1) g`, nUsers)
	// status: 50% paid, 30% shipped, 15% pending, 5% cancelled; shipped_at null ~70%.
	mustExec(t, pool, `INSERT INTO orders (user_id, status, total, shipped_at)
SELECT 1 + (g % $1),
  (CASE WHEN g % 20 < 10 THEN 'paid' WHEN g % 20 < 16 THEN 'shipped' WHEN g % 20 < 19 THEN 'pending' ELSE 'cancelled' END)::order_status,
  (g % 500) + 0.99,
  CASE WHEN g % 10 < 3 THEN now() END
FROM generate_series(1, $2) g`, nUsers, nOrders)
	mustExec(t, pool, `INSERT INTO billing."Invoices" (user_id, "AmountDue")
SELECT 1 + (g % $1), g FROM generate_series(1, 100) g`, nUsers)
	mustExec(t, pool, "ANALYZE")
}

func TestIntegrationStats(t *testing.T) {
	pool := newTestDB(t, true)
	seed(t, pool, 2000, 20000)

	p, err := Collect(context.Background(), pool, Options{SampleInterval: 200 * time.Millisecond})
	if err != nil {
		t.Fatalf("Collect: %v", err)
	}
	orders := findTable(p, "public.orders")
	users := findTable(p, "public.users")
	if orders == nil || users == nil {
		t.Fatalf("tables missing: %+v", p.Tables)
	}
	if orders.RowEstimate < 19000 || orders.RowEstimate > 21000 {
		t.Errorf("orders RowEstimate = %d, want ~20000", orders.RowEstimate)
	}
	if users.RowEstimate < 1900 || users.RowEstimate > 2100 {
		t.Errorf("users RowEstimate = %d, want ~2000", users.RowEstimate)
	}
	if orders.TotalBytes <= 0 {
		t.Errorf("orders TotalBytes = %d", orders.TotalBytes)
	}

	status := findColumn(orders, "status")
	if status == nil {
		t.Fatal("no status column")
	}
	if status.Sensitive {
		t.Errorf("status marked sensitive")
	}
	if status.DataType != "public.order_status" && status.DataType != "order_status" {
		t.Errorf("status DataType = %q", status.DataType)
	}
	if len(status.MostCommonVals) != 4 || len(status.MostCommonFreqs) != 4 {
		t.Fatalf("status MCVs = %v / %v", status.MostCommonVals, status.MostCommonFreqs)
	}
	freq := map[string]float64{}
	for i, v := range status.MostCommonVals {
		freq[v] = status.MostCommonFreqs[i]
	}
	if math.Abs(freq["paid"]-0.5) > 0.05 || math.Abs(freq["cancelled"]-0.05) > 0.03 {
		t.Errorf("status freqs = %v", freq)
	}

	shipped := findColumn(orders, "shipped_at")
	if shipped == nil || math.Abs(shipped.NullFrac-0.7) > 0.05 {
		t.Errorf("shipped_at NullFrac = %+v, want ~0.7", shipped)
	}
	if !shipped.Nullable {
		t.Errorf("shipped_at should be nullable")
	}
	if total := findColumn(orders, "total"); total == nil || len(total.HistogramBounds) == 0 && len(total.MostCommonVals) == 0 {
		t.Errorf("total has no value distribution: %+v", total)
	}
	if id := findColumn(orders, "id"); id == nil || id.NDistinct != -1 || id.Nullable {
		t.Errorf("orders.id stats = %+v", id)
	}

	for _, name := range []string{"email", "name"} {
		c := findColumn(users, name)
		if c == nil {
			t.Fatalf("users.%s missing", name)
		}
		if !c.Sensitive {
			t.Errorf("users.%s not Sensitive", name)
		}
		if c.MostCommonVals != nil || c.MostCommonFreqs != nil || c.HistogramBounds != nil {
			t.Errorf("users.%s leaks values: %+v", name, c)
		}
		if c.AvgWidth == 0 {
			t.Errorf("users.%s AvgWidth not kept", name)
		}
	}

	// The serialized profile never contains a raw email address.
	path := t.TempDir() + "/p.json"
	if err := Save(path, p); err != nil {
		t.Fatal(err)
	}
	raw, _ := os.ReadFile(path)
	if strings.Contains(string(raw), "@example.com") {
		t.Errorf("saved profile contains email values")
	}
}

// drive calls fn about rate times per second until ctx is done; it returns the call count.
func drive(ctx context.Context, wg *sync.WaitGroup, rate int, fn func(context.Context) error, errs chan<- error) *atomic.Int64 {
	var n atomic.Int64
	wg.Add(1)
	go func() {
		defer wg.Done()
		tick := time.NewTicker(time.Second / time.Duration(rate))
		defer tick.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-tick.C:
				if err := fn(ctx); err != nil && ctx.Err() == nil {
					select {
					case errs <- err:
					default:
					}
					return
				}
				n.Add(1)
			}
		}
	}()
	return &n
}

func TestIntegrationRates(t *testing.T) {
	pool := newTestDB(t, true)
	seed(t, pool, 1000, 2000)
	ctx := context.Background()

	loadCtx, stop := context.WithCancel(ctx)
	defer stop()
	var wg sync.WaitGroup
	errs := make(chan error, 4)
	drive(loadCtx, &wg, 50, func(ctx context.Context) error {
		var name string
		err := pool.QueryRow(ctx, "SELECT name FROM users WHERE id = $1", 1+rand.Intn(1000)).Scan(&name)
		return err
	}, errs)
	drive(loadCtx, &wg, 10, func(ctx context.Context) error {
		_, err := pool.Exec(ctx, "INSERT INTO orders (user_id, total) VALUES ($1, $2)", 1+rand.Intn(1000), 12.5)
		return err
	}, errs)
	drive(loadCtx, &wg, 20, func(ctx context.Context) error {
		var n int64
		return pool.QueryRow(ctx, `SELECT count(*) FROM billing."Invoices" WHERE user_id = $1`, 1+rand.Intn(1000)).Scan(&n)
	}, errs)
	time.Sleep(500 * time.Millisecond) // let both drivers reach steady state

	p, err := Collect(ctx, pool, Options{
		SampleInterval: 3 * time.Second,
		FeatureMap: map[string]string{
			`from\s+users`:           "profile-page",
			`insert\s+into\s+orders`: "checkout",
		},
	})
	stop()
	wg.Wait()
	select {
	case err := <-errs:
		t.Fatalf("load: %v", err)
	default:
	}
	if err != nil {
		t.Fatalf("Collect: %v", err)
	}

	var sel, ins, inv *model.QueryProfile
	for i := range p.Queries {
		q := &p.Queries[i]
		t.Logf("query %.1f/s %.3fms %v %q: %s", q.CallsPerSec, q.MeanMs, q.Tables, q.Feature, q.Query)
		if strings.Contains(q.Query, "pg-rehearse") || reCatalogRef.MatchString(q.Query) {
			t.Errorf("collector/catalog query leaked into profile: %q", q.Query)
		}
		low := strings.ToLower(q.Query)
		switch {
		case strings.HasPrefix(low, "select name from users"):
			sel = q
		case strings.HasPrefix(low, "insert into orders"):
			ins = q
		case strings.Contains(q.Query, `billing."Invoices"`):
			inv = q
		}
	}
	if sel == nil || ins == nil || inv == nil {
		t.Fatalf("expected queries not found: %+v", p.Queries)
	}
	check := func(q *model.QueryProfile, rate float64, table, feature string) {
		t.Helper()
		if q.CallsPerSec < rate*0.7 || q.CallsPerSec > rate*1.3 {
			t.Errorf("%q CallsPerSec = %.1f, want %.0f±30%%", q.Query, q.CallsPerSec, rate)
		}
		if q.MeanMs <= 0 {
			t.Errorf("%q MeanMs = %v", q.Query, q.MeanMs)
		}
		if len(q.Tables) != 1 || q.Tables[0] != table {
			t.Errorf("%q Tables = %v, want [%s]", q.Query, q.Tables, table)
		}
		if q.Feature != feature {
			t.Errorf("%q Feature = %q, want %q", q.Query, q.Feature, feature)
		}
		if q.QueryID == 0 {
			t.Errorf("%q QueryID = 0", q.Query)
		}
		if !strings.Contains(q.Query, "$1") {
			t.Errorf("%q is not normalized", q.Query)
		}
	}
	check(sel, 50, "public.users", "profile-page")
	check(ins, 10, "public.orders", "checkout")
	check(inv, 20, "billing.Invoices", "")
	if p.Queries[0].QueryID != sel.QueryID {
		t.Errorf("queries not sorted by rate: first is %q", p.Queries[0].Query)
	}
}

func TestIntegrationLongTxn(t *testing.T) {
	pool := newTestDB(t, true)
	seed(t, pool, 100, 1000)
	ctx := context.Background()

	conn, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Release()
	tx, err := conn.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	var n int
	if err := tx.QueryRow(ctx, "SELECT count(*) FROM orders WHERE status = 'paid'").Scan(&n); err != nil {
		t.Fatal(err)
	}
	if err := tx.QueryRow(ctx, `SELECT count(*) FROM billing."Invoices"`).Scan(&n); err != nil {
		t.Fatal(err)
	}
	if err := tx.QueryRow(ctx, "SELECT count(*) FROM orders WHERE status = 'paid'").Scan(&n); err != nil {
		t.Fatal(err)
	}
	done := make(chan struct{})
	go func() {
		defer close(done)
		time.Sleep(4500 * time.Millisecond)
		_ = tx.Commit(ctx)
	}()

	p, err := Collect(ctx, pool, Options{SampleInterval: 3 * time.Second, LongTxnMinSec: 1})
	<-done
	if err != nil {
		t.Fatalf("Collect: %v", err)
	}
	if len(p.LongTxns) != 1 {
		t.Fatalf("LongTxns = %+v, want exactly 1", p.LongTxns)
	}
	lt := p.LongTxns[0]
	if !strings.Contains(strings.ToLower(lt.Query), "from orders") {
		t.Errorf("LongTxn query = %q", lt.Query)
	}
	if lt.DurationSec < 2.5 {
		t.Errorf("LongTxn DurationSec = %.2f, want >= 2.5", lt.DurationSec)
	}
	hasOrders := false
	for _, tb := range lt.Tables {
		if tb == "public.orders" {
			hasOrders = true
		}
		if !strings.Contains(tb, ".") {
			t.Errorf("LongTxn table %q not schema-qualified", tb)
		}
	}
	if !hasOrders || !containsStr(lt.Tables, "billing.Invoices") {
		t.Errorf("LongTxn Tables = %v, want public.orders and billing.Invoices (same unquoted form as QueryProfile.Tables)", lt.Tables)
	}
	if lt.PerHour <= 0 {
		t.Errorf("LongTxn PerHour = %v", lt.PerHour)
	}
}

func TestIntegrationNoPgStatStatements(t *testing.T) {
	pool := newTestDB(t, false)
	mustExec(t, pool, fixtureSchema)
	_, err := Collect(context.Background(), pool, Options{SampleInterval: 100 * time.Millisecond})
	if err == nil {
		t.Fatal("Collect succeeded without pg_stat_statements")
	}
	if !errors.Is(err, ErrNoPgStatStatements) {
		t.Errorf("error does not wrap ErrNoPgStatStatements: %v", err)
	}
	if !strings.Contains(err.Error(), "CREATE EXTENSION pg_stat_statements") {
		t.Errorf("error lacks remedy: %v", err)
	}
}

func containsStr(xs []string, x string) bool {
	for _, v := range xs {
		if v == x {
			return true
		}
	}
	return false
}
