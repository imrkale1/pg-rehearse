// userNamespaceFilter restricts a query on pg_namespace alias n to user schemas.
const userNamespaceFilter = `n.nspname NOT IN ('pg_catalog','information_schema','pg_toast')
  AND n.nspname NOT LIKE 'pg_temp_%' AND n.nspname NOT LIKE 'pg_toast_temp_%'`

// notExtensionMember excludes objects (alias-qualified oid expr, catalog) owned by an extension.
func notExtensionMember(oidExpr, catalog string) string {
	return fmt.Sprintf(`NOT EXISTS (SELECT 1 FROM pg_depend de
  WHERE de.classid = '%s'::regclass AND de.objid = %s AND de.deptype = 'e')`, catalog, oidExpr)
}

// generateSchemaSQL builds schema-only DDL from the system catalogs. The
// transaction must have search_path = pg_catalog so that every name emitted by
// format_type/pg_get_expr/pg_get_*def is schema-qualified.
//
// Order: schemas, extensions, enum/domain types, functions, sequences, tables
// (parents before partitions/children), sequence ownership, PK/unique/check/
// exclusion constraints, table indexes, foreign keys, views/matviews
// (dependency order), matview indexes, triggers.
func generateSchemaSQL(ctx context.Context, tx pgx.Tx) (string, error) {
	var b strings.Builder
	b.WriteString("-- schema generated by pg-rehearse from system catalogs (no data)\n")
	b.WriteString("SET check_function_bodies = false;\n\n")
	emit := func(stmt string) {
		stmt = strings.TrimSpace(stmt)
		stmt = strings.TrimRight(stmt, ";")
		b.WriteString(stmt)
		b.WriteString(";\n\n")
	}
	steps := []func(context.Context, pgx.Tx, func(string)) error{
		ddlSchemas, ddlExtensions, ddlTypes, ddlFunctions, ddlSequences, ddlTables,
		ddlSequenceOwnership, ddlConstraintsNonFK, ddlTableIndexes, ddlForeignKeys,
		ddlViews, ddlMatviewIndexes, ddlTriggers,
	}
	for _, step := range steps {
		if err := step(ctx, tx, emit); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

func queryStrings(ctx context.Context, tx pgx.Tx, sql string, emit func(string)) error {
	rows, err := tx.Query(ctx, sql)
	if err != nil {
		return fmt.Errorf("schema query failed: %w\n%s", err, sql)
	}
	stmts, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		return fmt.Errorf("schema query failed: %w", err)
	}
	for _, s := range stmts {
		emit(s)
	}
	return nil
}

func ddlSchemas(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT format('CREATE SCHEMA IF NOT EXISTS %I', n.nspname)
FROM pg_namespace n WHERE `+userNamespaceFilter+` AND `+notExtensionMember("n.oid", "pg_namespace")+`
ORDER BY n.nspname`, emit)
}

func ddlExtensions(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I', e.extname, n.nspname)
FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
WHERE e.extname <> 'plpgsql' ORDER BY e.extname`, emit)
}

func ddlTypes(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	// Enums first (domains may be based on them), then domains.
	if err := queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT format('CREATE TYPE %I.%I AS ENUM (%s)', n.nspname, t.typname,
  coalesce((SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder)
            FROM pg_enum e WHERE e.enumtypid = t.oid), ''))
FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
WHERE t.typtype = 'e' AND `+userNamespaceFilter+` AND `+notExtensionMember("t.oid", "pg_type")+`
ORDER BY t.oid`, emit); err != nil {
		return err
	}
	return queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT format('CREATE DOMAIN %I.%I AS %s%s%s%s', n.nspname, t.typname,
  format_type(t.typbasetype, t.typtypmod),
  CASE WHEN t.typcollation <> 0 AND t.typcollation <> bt.typcollation
       THEN (SELECT format(' COLLATE %I.%I', cn.nspname, c.collname) FROM pg_collation c
             JOIN pg_namespace cn ON cn.oid = c.collnamespace WHERE c.oid = t.typcollation)
       ELSE '' END,
  CASE WHEN t.typdefaultbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(t.typdefaultbin, 0) ELSE '' END,
  CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END)
  || coalesce((SELECT string_agg(format(' CONSTRAINT %I %s', co.conname, pg_get_constraintdef(co.oid)), '' ORDER BY co.conname)
               FROM pg_constraint co WHERE co.contypid = t.oid AND co.contype = 'c'), '')
FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
JOIN pg_type bt ON bt.oid = t.typbasetype
WHERE t.typtype = 'd' AND `+userNamespaceFilter+` AND `+notExtensionMember("t.oid", "pg_type")+`
ORDER BY t.oid`, emit)
}

func ddlFunctions(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT pg_get_functiondef(p.oid)
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
JOIN pg_language l ON l.oid = p.prolang
WHERE p.prokind IN ('f','p') AND l.lanname NOT IN ('internal','c')
  AND `+userNamespaceFilter+` AND `+notExtensionMember("p.oid", "pg_proc")+`
ORDER BY p.oid`, emit)
}

// ddlSequences emits standalone and serial-owned sequences. Identity sequences
// (pg_depend deptype 'i') are created implicitly by GENERATED ... AS IDENTITY.
func ddlSequences(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT format('CREATE SEQUENCE %I.%I AS %s START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s%s',
  n.nspname, c.relname, format_type(s.seqtypid, NULL), s.seqstart, s.seqincrement,
  s.seqmin, s.seqmax, s.seqcache, CASE WHEN s.seqcycle THEN ' CYCLE' ELSE ' NO CYCLE' END)
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_sequence s ON s.seqrelid = c.oid
WHERE c.relkind = 'S' AND `+userNamespaceFilter+` AND `+notExtensionMember("c.oid", "pg_class")+`
  AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_class'::regclass
                  AND d.objid = c.oid AND d.deptype = 'i')
ORDER BY n.nspname, c.relname`, emit)
}

func ddlSequenceOwnership(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT format('ALTER SEQUENCE %I.%I OWNED BY %I.%I.%I', n.nspname, c.relname, tn.nspname, t.relname, a.attname)
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_depend d ON d.classid = 'pg_class'::regclass AND d.objid = c.oid AND d.deptype = 'a'
  AND d.refclassid = 'pg_class'::regclass AND d.refobjsubid > 0
JOIN pg_class t ON t.oid = d.refobjid JOIN pg_namespace tn ON tn.oid = t.relnamespace
JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
WHERE c.relkind = 'S' AND `+userNamespaceFilter+` AND `+notExtensionMember("c.oid", "pg_class")+`
ORDER BY n.nspname, c.relname`, emit)
}

type tableDef struct {
	oid     uint32
	qname   string
	parents []uint32
	stmt    string
}

// ddlTables emits CREATE TABLE for ordinary and partitioned tables, with
// partitions (PARTITION OF) and inheritance children after their parents.
func ddlTables(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	rows, err := tx.Query(ctx, `/* pg-rehearse:profile */
SELECT c.oid, format('%I.%I', n.nspname, c.relname), c.relkind::text, c.relpersistence::text, c.relispartition,
  CASE WHEN c.relispartition THEN pg_get_expr(c.relpartbound, c.oid) END,
  CASE WHEN c.relkind = 'p' THEN pg_get_partkeydef(c.oid) END,
  coalesce((SELECT array_agg(i.inhparent ORDER BY i.inhseqno) FROM pg_inherits i WHERE i.inhrelid = c.oid), '{}'),
  coalesce((SELECT array_agg(format('%I.%I', pn.nspname, p.relname) ORDER BY i.inhseqno)
            FROM pg_inherits i JOIN pg_class p ON p.oid = i.inhparent JOIN pg_namespace pn ON pn.oid = p.relnamespace
            WHERE i.inhrelid = c.oid), '{}'),
  array_to_string(c.reloptions, ', ')
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ('r','p') AND `+userNamespaceFilter+` AND `+notExtensionMember("c.oid", "pg_class")+`
ORDER BY n.nspname, c.relname`)
	if err != nil {
		return fmt.Errorf("list tables: %w", err)
	}
	type rawTable struct {
		oid                     uint32
		qname, kind, persist    string
		isPart                  bool
		bound, partkey, relopts *string
		parents                 []uint32
		parentNames             []string
	}
	var raws []rawTable
	for rows.Next() {
		var r rawTable
		if err := rows.Scan(&r.oid, &r.qname, &r.kind, &r.persist, &r.isPart, &r.bound, &r.partkey,
			&r.parents, &r.parentNames, &r.relopts); err != nil {
			rows.Close()
			return err
		}
		raws = append(raws, r)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return err
	}

	var defs []tableDef
	for _, r := range raws {
		cols, err := columnDefs(ctx, tx, r.oid, r.isPart)
		if err != nil {
			return err
		}
		var s strings.Builder
		s.WriteString("CREATE ")
		if r.persist == "u" {
			s.WriteString("UNLOGGED ")
		}
		s.WriteString("TABLE " + r.qname)
		if r.isPart && len(r.parentNames) > 0 {
			s.WriteString(" PARTITION OF " + r.parentNames[0])
			if len(cols) > 0 {
				s.WriteString(" (\n    " + strings.Join(cols, ",\n    ") + "\n)")
			}
			if r.bound != nil {
				s.WriteString(" " + *r.bound)
			}
		} else {
			s.WriteString(" (\n    " + strings.Join(cols, ",\n    ") + "\n)")
			if len(r.parentNames) > 0 {
				s.WriteString(" INHERITS (" + strings.Join(r.parentNames, ", ") + ")")
			}
		}
		if r.partkey != nil {
			s.WriteString(" PARTITION BY " + *r.partkey)
		}
		if r.relopts != nil && *r.relopts != "" {
			s.WriteString(" WITH (" + *r.relopts + ")")
		}
		defs = append(defs, tableDef{oid: r.oid, qname: r.qname, parents: r.parents, stmt: s.String()})
	}

	// Emit parents before children.
	done := map[uint32]bool{}
	inSet := map[uint32]bool{}
	for _, d := range defs {
		inSet[d.oid] = true
	}
	for len(done) < len(defs) {
		progress := false
		for _, d := range defs {
			if done[d.oid] {
				continue
			}
			ready := true
			for _, p := range d.parents {
				if inSet[p] && !done[p] {
					ready = false
				}
			}
			if ready {
				emit(d.stmt)
				done[d.oid] = true
				progress = true
			}
		}
		if !progress {
			return fmt.Errorf("cyclic table inheritance")
		}
	}
	return nil
}

// columnDefs returns column definitions for one table. For partitions only
// locally-specified defaults are emitted as "col WITH OPTIONS DEFAULT ...".
func columnDefs(ctx context.Context, tx pgx.Tx, relid uint32, isPartition bool) ([]string, error) {
	rows, err := tx.Query(ctx, `/* pg-rehearse:profile */
SELECT quote_ident(a.attname), format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attislocal,
  a.attidentity::text, a.attgenerated::text,
  CASE WHEN a.atthasdef THEN pg_get_expr(ad.adbin, ad.adrelid) END,
  CASE WHEN a.attcollation <> 0 AND a.attcollation <> t.typcollation
       THEN (SELECT format('%I.%I', cn.nspname, co.collname) FROM pg_collation co
             JOIN pg_namespace cn ON cn.oid = co.collnamespace WHERE co.oid = a.attcollation) END
FROM pg_attribute a
JOIN pg_type t ON t.oid = a.atttypid
LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`, relid)
	if err != nil {
		return nil, fmt.Errorf("columns: %w", err)
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var name, typ, identity, generated string
		var notNull, local bool
		var def, coll *string
		if err := rows.Scan(&name, &typ, &notNull, &local, &identity, &generated, &def, &coll); err != nil {
			return nil, err
		}
		if isPartition {
			// Columns come from the parent; NOT NULL and defaults are inherited.
			continue
		}
		if !local {
			continue // inherited via INHERITS
		}
		col := name + " " + typ
		if coll != nil {
			col += " COLLATE " + *coll
		}
		switch generated {
		case "s":
			if def != nil {
				col += " GENERATED ALWAYS AS (" + *def + ") STORED"
			}
		case "v":
			if def != nil {
				col += " GENERATED ALWAYS AS (" + *def + ") VIRTUAL"
			}
		default:
			if def != nil {
				col += " DEFAULT " + *def
			}
		}
		switch identity {
		case "a":
			col += " GENERATED ALWAYS AS IDENTITY"
		case "d":
			col += " GENERATED BY DEFAULT AS IDENTITY"
		}
		if notNull {
			col += " NOT NULL"
		}
		out = append(out, col)
	}
	return out, rows.Err()
}

const userTableConstraintBase = `/* pg-rehearse:profile */
SELECT format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s',
  n.nspname, c.relname, co.conname, pg_get_constraintdef(co.oid))
FROM pg_constraint co
JOIN pg_class c ON c.oid = co.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ('r','p') AND co.conislocal AND co.conparentid = 0
  AND ` + userNamespaceFilter

func ddlConstraintsNonFK(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, userTableConstraintBase+` AND `+notExtensionMember("c.oid", "pg_class")+`
  AND co.contype IN ('p','u','x','c')
ORDER BY CASE co.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'x' THEN 2 ELSE 3 END, n.nspname, c.relname, co.conname`, emit)
}

func ddlForeignKeys(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, userTableConstraintBase+` AND `+notExtensionMember("c.oid", "pg_class")+`
  AND co.contype = 'f'
ORDER BY n.nspname, c.relname, co.conname`, emit)
}

// indexQuery lists indexes not backed by a constraint and not attached
// partitions of a partitioned index (those are created by the parent index).
func indexQuery(relkinds string) string {
	return `/* pg-rehearse:profile */
SELECT replace(pg_get_indexdef(i.indexrelid), ' ON ONLY ', ' ON ')
FROM pg_index i
JOIN pg_class ic ON ic.oid = i.indexrelid
JOIN pg_class c ON c.oid = i.indrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN (` + relkinds + `) AND ` + userNamespaceFilter + ` AND ` + notExtensionMember("c.oid", "pg_class") + `
  AND NOT EXISTS (SELECT 1 FROM pg_constraint co WHERE co.conindid = i.indexrelid AND co.contype IN ('p','u','x'))
  AND NOT EXISTS (SELECT 1 FROM pg_inherits ih WHERE ih.inhrelid = i.indexrelid)
ORDER BY n.nspname, c.relname, ic.relname`
}

func ddlTableIndexes(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, indexQuery(`'r','p'`), emit)
}

func ddlMatviewIndexes(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, indexQuery(`'m'`), emit)
}

// ddlViews emits views and materialized views in dependency order.
func ddlViews(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	rows, err := tx.Query(ctx, `/* pg-rehearse:profile */
SELECT c.oid,
  CASE WHEN c.relkind = 'v'
    THEN format('CREATE VIEW %I.%I%s AS %s', n.nspname, c.relname,
                CASE WHEN c.reloptions IS NOT NULL THEN ' WITH (' || array_to_string(c.reloptions, ', ') || ')' ELSE '' END,
                rtrim(btrim(pg_get_viewdef(c.oid)), ';'))
    ELSE format('CREATE MATERIALIZED VIEW %I.%I AS %s WITH NO DATA', n.nspname, c.relname,
                rtrim(btrim(pg_get_viewdef(c.oid)), ';'))
  END,
  coalesce((SELECT array_agg(DISTINCT d.refobjid) FROM pg_rewrite r
            JOIN pg_depend d ON d.classid = 'pg_rewrite'::regclass AND d.objid = r.oid
              AND d.refclassid = 'pg_class'::regclass
            WHERE r.ev_class = c.oid AND d.refobjid <> c.oid), '{}')
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ('v','m') AND `+userNamespaceFilter+` AND `+notExtensionMember("c.oid", "pg_class")+`
ORDER BY c.oid`)
	if err != nil {
		return fmt.Errorf("list views: %w", err)
	}
	type view struct {
		oid  uint32
		stmt string
		deps []uint32
	}
	var views []view
	for rows.Next() {
		var v view
		if err := rows.Scan(&v.oid, &v.stmt, &v.deps); err != nil {
			rows.Close()
			return err
		}
		views = append(views, v)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return err
	}
	isView := map[uint32]bool{}
	for _, v := range views {
		isView[v.oid] = true
	}
	done := map[uint32]bool{}
	for len(done) < len(views) {
		progress := false
		for _, v := range views {
			if done[v.oid] {
				continue
			}
			ready := true
			for _, d := range v.deps {
				if isView[d] && !done[d] {
					ready = false
				}
			}
			if ready {
				emit(v.stmt)
				done[v.oid] = true
				progress = true
			}
		}
		if !progress {
			// Should not happen; fall back to oid order for the rest.
			rest := []view{}
			for _, v := range views {
				if !done[v.oid] {
					rest = append(rest, v)
				}
			}
			sort.Slice(rest, func(i, j int) bool { return rest[i].oid < rest[j].oid })
			for _, v := range rest {
				emit(v.stmt)
				done[v.oid] = true
			}
		}
	}
	return nil
}

func ddlTriggers(ctx context.Context, tx pgx.Tx, emit func(string)) error {
	return queryStrings(ctx, tx, `/* pg-rehearse:profile */
SELECT pg_get_triggerdef(t.oid)
FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE NOT t.tgisinternal AND t.tgparentid = 0 AND `+userNamespaceFilter+` AND `+notExtensionMember("c.oid", "pg_class")+`
ORDER BY n.nspname, c.relname, t.tgname`, emit)
}
